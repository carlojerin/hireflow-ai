from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column

from backend.app.database.database import Base


# ============================================================
# JOBPILOT AI - PROGRAMMING TEST (Task 4C)
#
# Mirrors AptitudeTest's exact shape and conventions: one row
# per application (single unique FK, no relationship()), a
# JSON-as-Text `questions` column that includes hidden test
# cases (never returned to the candidate as-is — see
# sanitize_programming_question() in
# api/routes/programming_tests.py), a `question_source`
# provenance column ("ai" | "fallback"), and the same
# assigned/expires/started/completed timestamp shape as
# AptitudeTest — self-service generated (no separate HR-assign
# step exists for this stage), so assigned_at/started_at are
# both stamped at generation time and the test is immediately
# "in_progress", unlike AptitudeTest's HR-assign-then-candidate-
# start two-step flow.
# ============================================================

class ProgrammingTest(Base):

    __tablename__ = "programming_tests"

    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        index=True,
    )

    application_id: Mapped[int] = mapped_column(
        ForeignKey("job_applications.id"),
        nullable=False,
        unique=True,
        index=True,
    )

    # =========================================================
    # QUESTIONS
    #
    # JSON list of 3 question dicts, each including
    # hidden_tests. Stripped before any candidate-facing API
    # response — this column is server-only, exactly like
    # AptitudeTest.questions includes correct_answer.
    # =========================================================

    questions: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    total_questions: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # =========================================================
    # RESULT
    #
    # score / total_score are both expressed in "points" where
    # each question is worth 100 points internally (so
    # total_score == total_questions * 100) — matches the
    # ProgrammingTest field names suggested in the task spec.
    # Overall percentage = score / total_score * 100.
    # =========================================================

    score: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
    )

    total_score: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
    )

    passed: Mapped[bool | None] = mapped_column(
        Boolean,
        nullable=True,
    )

    # =========================================================
    # STATUS
    #
    # in_progress | completed | expired
    # =========================================================

    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="in_progress",
    )

    # =========================================================
    # QUESTION SOURCE
    #
    # "ai" — generated by Gemini for this candidate/job/
    #        blueprint.
    # "fallback" — the fixed deterministic question bank was
    #        used (Gemini unavailable, errored, or returned
    #        invalid/unsafe data).
    # =========================================================

    question_source: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="fallback",
    )

    # =========================================================
    # TIMESTAMPS
    #
    # expires_at is always assigned_at + PROGRAMMING_DEADLINE_
    # MINUTES, computed server-side — the frontend timer is
    # purely visual (see services/assessment/
    # programming_integration.py).
    # =========================================================

    assigned_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    expires_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
    )

    started_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    submitted_at: Mapped[datetime | None] = mapped_column(
        DateTime,
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )
