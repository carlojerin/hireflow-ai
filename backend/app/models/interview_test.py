from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column

from backend.app.database.database import Base


# ============================================================
# JOBPILOT AI - INTERVIEW TEST (Task 4D)
#
# Mirrors ProgrammingTest's exact shape and conventions: one row
# per application (single unique FK, no relationship()), a
# JSON-as-Text `questions` column that includes server-only
# fields (expected_answer_points, follow_up_focus) never
# returned to the candidate as-is, a `question_source`
# provenance column ("ai" | "fallback"), and the same assigned/
# expires/started/submitted timestamp shape. Self-service
# generated (no HR-assign step), so the test is created already
# "in_progress" — identical to ProgrammingTest's own design.
#
# current_question_index is the one new concept this stage
# needs beyond ProgrammingTest's shape: the interview is
# delivered one question at a time, and the SERVER — not the
# candidate — decides which question is "current". See
# api/routes/interview_tests.py.
# ============================================================

class InterviewTest(Base):

    __tablename__ = "interview_tests"

    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        index=True,
    )

    application_id: Mapped[int] = mapped_column(
        ForeignKey("job_applications.id"),
        nullable=False,
        unique=True,
        index=True,
    )

    # =========================================================
    # QUESTIONS
    #
    # JSON list of 5 question dicts, each including
    # expected_answer_points/follow_up_focus. Stripped before
    # any candidate-facing API response.
    # =========================================================

    questions: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    total_questions: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # 0-based index of the next question the candidate has not
    # yet answered. Equal to total_questions once every question
    # has a stored InterviewResponse.
    current_question_index: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
    )

    # =========================================================
    # RESULT
    #
    # overall_score is the average of each question's server-
    # computed composite score (0-100). recommendation is a
    # deterministic, descriptive score-band label — never a
    # hiring verdict (see services/assessment/
    # interview_scoring.py).
    # =========================================================

    overall_score: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
    )

    passed: Mapped[bool | None] = mapped_column(
        Boolean,
        nullable=True,
    )

    recommendation: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
    )

    # JSON: aggregated {technical_correctness, understanding,
    # reasoning, relevance, communication, strengths, gaps} —
    # averaged/merged across all 5 answered questions.
    evaluation_summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # =========================================================
    # STATUS
    #
    # in_progress | completed | expired
    # =========================================================

    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="in_progress",
    )

    # =========================================================
    # QUESTION SOURCE
    #
    # "ai" — generated by Gemini for this candidate/job/
    #        blueprint.
    # "fallback" — the fixed deterministic question bank was
    #        used (Gemini unavailable, errored, or returned
    #        invalid data).
    # =========================================================

    question_source: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="fallback",
    )

    # =========================================================
    # TIMESTAMPS
    # =========================================================

    assigned_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    expires_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
    )

    started_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    submitted_at: Mapped[datetime | None] = mapped_column(
        DateTime,
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
    )
